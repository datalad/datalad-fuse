docs_source = dirname(abspath(__file__))
repo_root = dirname(dirname(docs_source))

# Generate the RST man pages for the commands (docs/source/generated/man/)
# with the helper from _datalad_buildsupport.
setup_py = opj(repo_root, "setup.py")
if exists(setup_py):
    subprocess.run(
        [
            sys.executable,
            setup_py,
            "build_manpage",
            "--cmdsuite",
            "datalad_fuse:command_suite",
            "--manpath",
            opj(repo_root, "build", "man"),
            "--rstpath",
            opj(docs_source, "generated", "man"),
        ],
        cwd=repo_root,
        check=True,
    )

# CHANGELOG.md is generated by `auto` from PR titles, some of which, such as
# "[gh-actions](deps): ...", read as Markdown links to a document "deps".
# changelog.rst includes a copy with such links escaped.
with open(opj(repo_root, "CHANGELOG.md"), encoding="utf-8") as f:
    _changelog = re.sub(r"\[([^]]+)\]\(([\w-]+)\)", r"\\[\1\\](\2)", f.read())
os.makedirs(opj(docs_source, "generated"), exist_ok=True)
with open(opj(docs_source, "generated", "CHANGELOG.md.inc"), "w", encoding="utf-8") as f:
    f.write(_changelog)

# Methods decorated with methodtools.lru_cache are hidden behind a descriptor
# that autodoc does not recognize as a method.  For the documentation only,
# replace them with the functions they wrap, so that they are documented.
for _cls in (datalad_fuse.fsspec.DatasetAdapter, datalad_fuse.fsspec.FsspecAdapter):
    for _name, _attr in list(vars(_cls).items()):
        if type(_attr).__module__.startswith("wirerope") and hasattr(
            _attr, "__wrapped__"
        ):
            setattr(_cls, _name, _attr.__wrapped__)

