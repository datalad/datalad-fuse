def _hide_edit_link(_app, pagename, _templatename, context, _doctree):
    # These pages are generated or included, so there is no source to edit
    if pagename.startswith("generated/") or pagename in (
        "changelog",
        "genindex",
        "search",
    ):
        context["display_github"] = False


def _hide_enum_signature(_app, what, name, _obj, _options, signature, ret):
    if what == "class" and name == "datalad_fuse.fsspec.FileState":
        return "", None
    return signature, ret


def setup(app):
    app.connect("html-page-context", _hide_edit_link)
    app.connect("autodoc-process-signature", _hide_enum_signature)
